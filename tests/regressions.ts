async function request(handler:typeof accountHandler,body:unknown,cookie='',origin='http://localhost:4173') {
  let status=200;let data:any;const headers:Record<string,unknown>={};
  const res={setHeader:(key:string,value:unknown)=>{headers[key]=value;},status:(n:number)=>{status=n;return res;},json:(v:unknown)=>{data=v;}};
  await handler({method:'POST',headers:{'content-type':'application/json',host:'localhost:4173',origin,cookie},body} as never,res as never);
  return {status,data,cookie:String(headers['Set-Cookie']??'').split(';')[0],headers};
}
